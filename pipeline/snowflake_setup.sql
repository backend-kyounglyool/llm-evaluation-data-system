-- Snowflake 1회 셋업: S3 raw 버킷 ↔ Snowflake storage integration + external stage + 최소 권한 롤
-- ACCOUNTADMIN으로 실행. 740255825084, skill-eval-lake-740255825084을 실제 값으로 교체.
-- 전 구문이 멱등이라 다시 실행해도 된다.

CREATE DATABASE IF NOT EXISTS SKILL_EVAL;
CREATE SCHEMA IF NOT EXISTS SKILL_EVAL.MART;
USE SCHEMA SKILL_EVAL.MART;

-- 1) S3 접근용 storage integration
CREATE STORAGE INTEGRATION IF NOT EXISTS SKILL_EVAL_S3
  TYPE = EXTERNAL_STAGE
  STORAGE_PROVIDER = 'S3'
  ENABLED = TRUE
  STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::740255825084:role/skill-eval-snowflake'
  STORAGE_ALLOWED_LOCATIONS = ('s3://skill-eval-lake-740255825084/raw/');

-- 2) DESC INTEGRATION SKILL_EVAL_S3; 결과의
--    STORAGE_AWS_IAM_USER_ARN / STORAGE_AWS_EXTERNAL_ID 를
--    AWS IAM role(skill-eval-snowflake)의 trust policy에 등록.
--    role 권한: s3:GetObject, s3:ListBucket (해당 버킷/raw/* 한정)

-- 3) raw JSONL 위 external stage
CREATE STAGE IF NOT EXISTS SKILL_EVAL_RAW_STAGE
  URL = 's3://skill-eval-lake-740255825084/raw/'
  STORAGE_INTEGRATION = SKILL_EVAL_S3
  FILE_FORMAT = (TYPE = JSON);

-- 4) 롤: 적재(ELT)와 조회(Grafana)를 나눈다. 둘 다 계정 수준 권한은 없다.
CREATE ROLE IF NOT EXISTS SKILL_EVAL_LOADER;
CREATE ROLE IF NOT EXISTS SKILL_EVAL_READER;
GRANT ROLE SKILL_EVAL_LOADER TO ROLE SYSADMIN;
GRANT ROLE SKILL_EVAL_READER TO ROLE SYSADMIN;

GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SKILL_EVAL_LOADER;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE SKILL_EVAL_READER;
GRANT USAGE ON DATABASE SKILL_EVAL TO ROLE SKILL_EVAL_LOADER;
GRANT USAGE ON DATABASE SKILL_EVAL TO ROLE SKILL_EVAL_READER;
GRANT USAGE ON SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_LOADER;
GRANT USAGE ON SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_READER;

-- 적재: 테이블 생성·교체, stage 읽기. STAGE·FILE FORMAT 생성은 write_pandas의 임시 객체용
GRANT CREATE TABLE, CREATE STAGE, CREATE FILE FORMAT ON SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_LOADER;
GRANT USAGE ON STAGE SKILL_EVAL_RAW_STAGE TO ROLE SKILL_EVAL_LOADER;

-- 조회: 현재·미래 테이블 SELECT만 (mart는 매시 CREATE OR REPLACE되므로 FUTURE 권한이 필요)
GRANT SELECT ON ALL TABLES IN SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_READER;
GRANT SELECT ON FUTURE TABLES IN SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_READER;

-- 5) 서비스 유저 전환. ACCOUNTADMIN으로 만든 기존 테이블이 있으면 소유권부터 넘긴다
--    (CREATE OR REPLACE는 소유자만 가능). 다른 관리자 계정이 있는지 확인한 뒤 실행.
GRANT OWNERSHIP ON ALL TABLES IN SCHEMA SKILL_EVAL.MART TO ROLE SKILL_EVAL_LOADER COPY CURRENT GRANTS;
GRANT ROLE SKILL_EVAL_LOADER TO USER SKILL_EVAL_ETL;
GRANT ROLE SKILL_EVAL_READER TO USER SKILL_EVAL_ETL;
-- 보조 롤을 비워야 READER 세션이 LOADER 권한을 함께 쓰지 못한다
ALTER USER SKILL_EVAL_ETL SET DEFAULT_ROLE = SKILL_EVAL_LOADER DEFAULT_SECONDARY_ROLES = ();
REVOKE ROLE ACCOUNTADMIN FROM USER SKILL_EVAL_ETL;
